// Inlines web/ into functions/web-assets.mjs so the Neon Function serves the PWA too
// (the function bundle only contains imported modules, not loose files).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const webDir = path.join(root, 'web');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.webmanifest': 'application/manifest+json', '.json': 'application/json', '.ico': 'image/x-icon' };

const assets = {};
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (fs.statSync(file).isDirectory()) { walk(file); continue; }
    const type = TYPES[path.extname(name)];
    if (!type) continue;
    assets[`/${path.relative(webDir, file).split(path.sep).join('/')}`] = { type, b64: fs.readFileSync(file).toString('base64') };
  }
})(webDir);

const out = path.join(root, 'functions', 'web-assets.mjs');
fs.writeFileSync(out, `// Generated by scripts/bundle-web.mjs — do not edit.\nexport default ${JSON.stringify(assets)};\n`);
console.log(`bundled ${Object.keys(assets).length} web files → functions/web-assets.mjs`);
